#[cfg(test)]
mod tests {
    use super::tests_support::paramset_a_512;
    use super::*;

    #[test]
    fn generator_is_on_curve() {
        let c = paramset_a_512();
        assert!(c.is_on_curve(&c.generator()));
    }

    #[test]
    fn scalar_mul_distributes_over_addition() {
        let c = paramset_a_512();
        let g = c.generator();
        // (2G) + (3G) == 5G
        let g2 = c.scalar_mul(&BigUint::from(2u32), &g);
        let g3 = c.scalar_mul(&BigUint::from(3u32), &g);
        let g5a = c.add(&g2, &g3);
        let g5b = c.scalar_mul(&BigUint::from(5u32), &g);
        assert_eq!(g5a, g5b);
        assert!(c.is_on_curve(&g5a));
    }

    #[test]
    fn scalar_mul_by_q_is_infinity() {
        let c = paramset_a_512();
        let qg = c.scalar_mul(&c.q.clone(), &c.generator());
        assert_eq!(qg, Point::Infinity);
    }

    #[test]
    fn point_le_roundtrips() {
        let c = paramset_a_512();
        let g2 = c.scalar_mul(&BigUint::from(2u32), &c.generator());
        let bytes = c.encode_point_le(&g2).unwrap();
        assert_eq!(bytes.len(), 2 * c.field_bytes);
        let back = c.decode_point_le(&bytes).unwrap();
        assert_eq!(g2, back);
    }

    #[test]
    fn tc26_256_generators_on_curve_and_prime_order() {
        for c in [
            tc26_256_paramset_b(),
            tc26_256_paramset_c(),
            tc26_256_paramset_d(),
        ] {
            assert_eq!(c.field_bytes, 32, "256-bit field");
            assert!(c.is_on_curve(&c.generator()), "generator must lie on curve");
            // q * G == O proves the published subgroup order matches the generator.
            assert_eq!(
                c.scalar_mul(&c.q.clone(), &c.generator()),
                Point::Infinity,
                "q*G must be the identity"
            );
        }
    }

    #[test]
    fn curve_lookup_resolves_known_param_sets() {
        assert_eq!(
            curve_for_param_set(&[1, 2, 643, 2, 2, 35, 1]),
            Some(tc26_256_paramset_b())
        );
        assert_eq!(
            curve_for_param_set(&[1, 2, 643, 7, 1, 2, 1, 1, 1]),
            Some(tc26_256_paramset_b())
        );
        assert_eq!(
            curve_for_param_set(&[1, 2, 643, 2, 2, 35, 2]),
            Some(tc26_256_paramset_c())
        );
        assert_eq!(
            curve_for_param_set(&[1, 2, 643, 2, 2, 35, 3]),
            Some(tc26_256_paramset_d())
        );
        assert_eq!(curve_for_param_set(&[1, 2, 643, 99]), None);
    }
}
