//! Software GOST R 34.10-2012 elliptic-curve arithmetic over a prime field in
//! short Weierstrass form `y^2 = x^3 + a*x + b (mod p)`.
//!
//! This is the minimal EC layer needed for the RFC 9189 CNT_IMIT key transport:
//! an **ephemeral** key pair is generated on the *server's* curve and a
//! Diffie-Hellman shared point is computed with VKO (see [`crate::gost_vko`]).
//! The cofactor of every GOST curve used here is 1 (`m == q`), so cofactor
//! multiplication is the identity and is omitted.
//!
//! Coordinates and scalars are [`BigUint`]. GOST stores curve points and keys
//! **little-endian**; helpers convert between that wire form and the integers
//! used for the math.

use num_bigint::BigUint;
use num_integer::Integer;
use num_traits::{One, Zero};

/// A prime-field short-Weierstrass curve with a generator of prime order `q`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Curve {
    /// Field characteristic (prime modulus).
    pub p: BigUint,
    /// Curve coefficient `a`.
    pub a: BigUint,
    /// Curve coefficient `b`.
    pub b: BigUint,
    /// Order of the cyclic subgroup generated by `(gx, gy)`.
    pub q: BigUint,
    /// Generator x-coordinate.
    pub gx: BigUint,
    /// Generator y-coordinate.
    pub gy: BigUint,
    /// Coordinate size in bytes (field element width on the wire).
    pub field_bytes: usize,
}

/// An affine point on a [`Curve`], or the point at infinity.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Point {
    /// The identity element.
    Infinity,
    /// An affine point `(x, y)`.
    Affine { x: BigUint, y: BigUint },
}

#[inline]
fn mod_add(a: &BigUint, b: &BigUint, p: &BigUint) -> BigUint {
    (a + b) % p
}

#[inline]
fn mod_sub(a: &BigUint, b: &BigUint, p: &BigUint) -> BigUint {
    // a, b are already reduced mod p; compute (a - b) mod p without going negative.
    let a = a % p;
    let b = b % p;
    if a >= b { a - b } else { (a + p) - b }
}

#[inline]
fn mod_mul(a: &BigUint, b: &BigUint, p: &BigUint) -> BigUint {
    (a * b) % p
}

/// Modular inverse via Fermat's little theorem (`p` is prime): `a^(p-2) mod p`.
#[inline]
fn mod_inv(a: &BigUint, p: &BigUint) -> BigUint {
    let exp = p - 2u32;
    a.modpow(&exp, p)
}

impl Curve {
    /// Construct a curve from already-parsed parameters.
    pub fn new(p: BigUint, a: BigUint, b: BigUint, q: BigUint, gx: BigUint, gy: BigUint) -> Self {
        let field_bytes = p.to_bytes_be().len();
        Curve {
            p,
            a,
            b,
            q,
            gx,
            gy,
            field_bytes,
        }
    }

    /// The generator point `P`.
    pub fn generator(&self) -> Point {
        Point::Affine {
            x: self.gx.clone(),
            y: self.gy.clone(),
        }
    }

    /// Test whether an affine point satisfies the curve equation.
    pub fn is_on_curve(&self, point: &Point) -> bool {
        match point {
            Point::Infinity => true,
            Point::Affine { x, y } => {
                let lhs = mod_mul(y, y, &self.p);
                let x3 = mod_mul(&mod_mul(x, x, &self.p), x, &self.p);
                let ax = mod_mul(&self.a, x, &self.p);
                let rhs = mod_add(&mod_add(&x3, &ax, &self.p), &self.b, &self.p);
                lhs == rhs
            }
        }
    }

    /// Point doubling.
    fn double(&self, point: &Point) -> Point {
        match point {
            Point::Infinity => Point::Infinity,
            Point::Affine { x, y } => {
                if y.is_zero() {
                    return Point::Infinity;
                }
                // lambda = (3*x^2 + a) / (2*y)
                let three = BigUint::from(3u32);
                let x2 = mod_mul(x, x, &self.p);
                let num = mod_add(&mod_mul(&three, &x2, &self.p), &self.a, &self.p);
                let den = mod_mul(&BigUint::from(2u32), y, &self.p);
                let lambda = mod_mul(&num, &mod_inv(&den, &self.p), &self.p);
                self.from_lambda(&lambda, x, y, x)
            }
        }
    }

    /// Point addition.
    pub fn add(&self, a: &Point, b: &Point) -> Point {
        match (a, b) {
            (Point::Infinity, _) => b.clone(),
            (_, Point::Infinity) => a.clone(),
            (Point::Affine { x: x1, y: y1 }, Point::Affine { x: x2, y: y2 }) => {
                if x1 == x2 {
                    // Either doubling or P + (-P) = O.
                    if y1 == y2 {
                        return self.double(a);
                    }
                    return Point::Infinity;
                }
                // lambda = (y2 - y1) / (x2 - x1)
                let num = mod_sub(y2, y1, &self.p);
                let den = mod_sub(x2, x1, &self.p);
                let lambda = mod_mul(&num, &mod_inv(&den, &self.p), &self.p);
                self.from_lambda2(&lambda, x1, y1, x2)
            }
        }
    }

    /// `x3 = lambda^2 - x_a - x_b`, `y3 = lambda*(x_a - x3) - y_a` (doubling form).
    fn from_lambda(&self, lambda: &BigUint, xa: &BigUint, ya: &BigUint, xb: &BigUint) -> Point {
        let l2 = mod_mul(lambda, lambda, &self.p);
        let x3 = mod_sub(&mod_sub(&l2, xa, &self.p), xb, &self.p);
        let y3 = mod_sub(
            &mod_mul(lambda, &mod_sub(xa, &x3, &self.p), &self.p),
            ya,
            &self.p,
        );
        Point::Affine { x: x3, y: y3 }
    }

    /// Addition form of the chord-tangent update.
    fn from_lambda2(&self, lambda: &BigUint, x1: &BigUint, y1: &BigUint, x2: &BigUint) -> Point {
        let l2 = mod_mul(lambda, lambda, &self.p);
        let x3 = mod_sub(&mod_sub(&l2, x1, &self.p), x2, &self.p);
        let y3 = mod_sub(
            &mod_mul(lambda, &mod_sub(x1, &x3, &self.p), &self.p),
            y1,
            &self.p,
        );
        Point::Affine { x: x3, y: y3 }
    }

    /// Scalar multiplication `k * point` via left-to-right double-and-add.
    pub fn scalar_mul(&self, k: &BigUint, point: &Point) -> Point {
        if k.is_zero() {
            return Point::Infinity;
        }
        let mut result = Point::Infinity;
        let bits = k.bits();
        // Process from the most-significant bit down.
        for i in (0..bits).rev() {
            result = self.double(&result);
            if k.bit(i) {
                result = self.add(&result, point);
            }
        }
        result
    }

    /// Encode a field element little-endian, padded to `field_bytes`.
    pub fn encode_coord_le(&self, value: &BigUint) -> Vec<u8> {
        let mut le = value.to_bytes_le();
        le.resize(self.field_bytes, 0);
        le
    }

    /// Encode an affine point as `X_le ‖ Y_le` (GOST raw public-key form).
    pub fn encode_point_le(&self, point: &Point) -> Option<Vec<u8>> {
        match point {
            Point::Infinity => None,
            Point::Affine { x, y } => {
                let mut out = self.encode_coord_le(x);
                out.extend_from_slice(&self.encode_coord_le(y));
                Some(out)
            }
        }
    }

    /// Decode an affine point from `X_le ‖ Y_le` (`2 * field_bytes`).
    pub fn decode_point_le(&self, bytes: &[u8]) -> Option<Point> {
        if bytes.len() != 2 * self.field_bytes {
            return None;
        }
        let x = BigUint::from_bytes_le(&bytes[..self.field_bytes]);
        let y = BigUint::from_bytes_le(&bytes[self.field_bytes..]);
        let point = Point::Affine { x, y };
        if self.is_on_curve(&point) {
            Some(point)
        } else {
            None
        }
    }
}

/// Reduce a scalar into `[1, q-1]` (rejection not needed: callers pass random
/// bytes and we reduce mod `q`, then map 0 → 1).
pub fn scalar_from_bytes_be(bytes: &[u8], q: &BigUint) -> BigUint {
    let mut k = BigUint::from_bytes_be(bytes) % q;
    if k.is_zero() {
        k = BigUint::one();
    }
    k
}

/// Whether `value` is a valid private scalar in `[1, q-1]`.
pub fn is_valid_scalar(value: &BigUint, q: &BigUint) -> bool {
    !value.is_zero() && value < q && value.gcd(q) == BigUint::one()
}

/// Parse a hex string (whitespace ignored) into a [`BigUint`].
fn from_hex(s: &str) -> BigUint {
    let cleaned: String = s.chars().filter(|c| c.is_ascii_hexdigit()).collect();
    BigUint::parse_bytes(cleaned.as_bytes(), 16).expect("valid hex constant")
}

