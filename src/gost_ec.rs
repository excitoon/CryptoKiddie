/// `id-tc26-gost-3410-2012-256-paramSetA` is a twisted-Edwards curve and is
/// rarely used for TLS server keys, so it is intentionally omitted here.
///
/// Look up a 256-bit curve by its `publicKeyParamSet` OID arcs. Returns `None`
/// for an unknown set (caller should report the OID).
pub fn curve_for_param_set(oid: &[u32]) -> Option<Curve> {
    // Legacy 2001 OIDs (1.2.643.2.2.35.x) and tc26 2012 OIDs (1.2.643.7.1.2.1.1.x).
    const A_2001: &[u32] = &[1, 2, 643, 2, 2, 35, 1];
    const B_2001: &[u32] = &[1, 2, 643, 2, 2, 35, 2];
    const C_2001: &[u32] = &[1, 2, 643, 2, 2, 35, 3];
    const XCH_A_2001: &[u32] = &[1, 2, 643, 2, 2, 36, 0];
    const XCH_B_2001: &[u32] = &[1, 2, 643, 2, 2, 36, 1];
    const B_2012: &[u32] = &[1, 2, 643, 7, 1, 2, 1, 1, 1]; // tc26 paramSetB
    const C_2012: &[u32] = &[1, 2, 643, 7, 1, 2, 1, 1, 2]; // tc26 paramSetC
    const D_2012: &[u32] = &[1, 2, 643, 7, 1, 2, 1, 1, 3]; // tc26 paramSetD
    match oid {
        o if o == A_2001 || o == XCH_A_2001 || o == B_2012 => Some(tc26_256_paramset_b()),
        o if o == B_2001 || o == XCH_B_2001 || o == C_2012 => Some(tc26_256_paramset_c()),
        o if o == C_2001 || o == D_2012 => Some(tc26_256_paramset_d()),
        _ => None,
    }
}

